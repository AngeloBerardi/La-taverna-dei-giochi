# Passo 13: il luogo come una piazza (tessere a griglia, un solo ottone) e il mercato come un banco (righe da 56 px).
async def sc_p13_luogo_mercato(b, srv):
    """Ventura: in città al più un ottone e tessere >= 44 px; mercato a banco con i data-v di sempre."""
    ctx = await new_context(b, srv.port); pg = await page(ctx, srv.url)
    await pg.evaluate("localStorage.removeItem('ven-salv')"); await pg.click('#plancia [data-v=avventura]'); await pg.wait_for_timeout(300)
    await pg.click('[data-a=ven][data-v="regno:sel"]'); await pg.click('[data-a=ven][data-v=nuova]')
    await pg.wait_for_function("VenArte.A.pronta||VenArte.A.fallita", timeout=30000)
    await pg.wait_for_function("VenMappa.K.scene&&document.getElementById('vn-ora')&&document.getElementById('vn-ora').textContent", timeout=30000)
    await pg.evaluate("""(()=>{const s=Ven.V.s,l=s.l.find(l=>l.tipo==='citta'&&l.faz==='tu')||s.l.find(l=>l.tipo==='citta');s.incontro=null;s.davanti=-1;s.dentro=l.id;l.noto=true;Ven.V.pan='luogo';Ven.V.sub='home';render()})()""")
    await pg.wait_for_selector('.vn-pan .vn-sr', timeout=5000)
    check(await pg.locator('.vn-pan .b.gold').count() == 1, 'in città un solo ottone')
    check(await pg.locator('[data-v="fai:esci"].gold').count() == 1, 'l\'ottone è Riparti')
    n = await pg.locator('.vn-sv').count()
    check(n >= 3, f'tessere dei servizi: {n}')
    pic = await pg.evaluate("[...document.querySelectorAll('.vn-sv')].filter(e=>{const r=e.getBoundingClientRect();return r.width<44||r.height<44}).length")
    check(pic == 0, f'tutte le tessere >= 44 px ({pic} piccole)')
    check(await pg.locator('[data-v="sub:mercato"]').count() == 1, 'tessera Mercato con il data-v di sempre')
    if os.environ.get('SCHERMATE_DIR'): await pg.screenshot(path=os.path.join(os.environ['SCHERMATE_DIR'], 'p13-citta.png'))
    await pg.click('[data-v="sub:mercato"]'); await pg.wait_for_selector('.vn-bn', timeout=5000)
    check(await pg.locator('.vn-bn').count() == 10, 'dieci righe di merce')
    h = await pg.evaluate("[...document.querySelectorAll('.vn-bn')].map(e=>Math.round(e.getBoundingClientRect().height))")
    check(all(x >= 56 for x in h), f'righe alte almeno 56 px: {h[:3]}')
    tasti = await pg.evaluate("[...document.querySelectorAll('.vn-wd')].filter(e=>{const r=e.getBoundingClientRect();return r.width<44||r.height<44}).length")
    check(tasti == 0, 'tasti + e − >= 44 px')
    check(await pg.locator('[data-v="fai:compra:grano"]').count() == 1 and await pg.locator('[data-v="fai:vendi:grano"]').count() == 1, 'data-v di compra e vendi invariati')
    if os.environ.get('SCHERMATE_DIR'): await pg.screenshot(path=os.path.join(os.environ['SCHERMATE_DIR'], 'p13-mercato.png'))
    await pg.click('[data-v="fai:compra:grano"]'); await pg.wait_for_timeout(150)
    check(not pg.errs, f'nessun errore di pagina: {pg.errs[:3]}')
    await ctx.close()
